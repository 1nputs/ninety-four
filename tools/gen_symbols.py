#!/usr/bin/env python3
"""Generate test/symbols_gen.h: ROM addresses of every code routine (SYM_name) and a table of
RAM symbol offsets for naming bytes in diffs."""
import json, pathlib, re, sys
P = pathlib.Path(__file__).resolve().parents[1]
syms = src = None
for cand in (P / 'build/asm/symbols.json', P / 'out/symbols.json'):
    if cand.exists():
        syms = json.load(open(cand)); src = cand; break
if syms is None:
    sys.exit('gen_symbols.py: no build/asm/symbols.json (tools/asm/build_vasm.sh writes it)')
for need in ('out/callgraph.json', 'out/ramwidths.json'):
    if not (P / need).exists():
        sys.exit('gen_symbols.py: no %s (make gen makes it)' % need)
# the segment stubs carry the retail address of every routine a segment calls outside itself
for stub in (P / 'ref/NHL94Genesis/src/stubinc').glob('*_stub.asm'):
    for line in stub.read_text(errors='replace').splitlines():
        m = re.match(r'^(\w+)\s*=\s*\$([0-9A-Fa-f]+)', line)
        if m and m.group(1) not in syms:
            syms[m.group(1)] = int(m.group(2), 16)
cg = json.load(open(P / 'out/callgraph.json'))
rows = json.load(open(P / 'out/ramwidths.json'))
code = [(n, syms[n]) for n, v in cg.items() if v.get('insns', 0) > 0 and n in syms and syms[n] < 0x100000]
code.sort(key=lambda t: t[1])
codenames = {n for n, _ in code}
data = sorted((n, a) for n, a in syms.items() if a < 0x100000 and n not in codenames and re.match(r'^[A-Za-z_]\w*$', n))
ram = sorted((r['addr'] - 0xFFFF0000, r['name']) for r in rows if 0xFFFF0000 <= r['addr'] < 0xFFFF0000 + 0x10000)
out = ['/* Generated by tools/gen_symbols.py from %s. Do not edit. */' % src.relative_to(P), '#pragma once', '#include <stdint.h>', '']
out += [f'#define SYM_{re.sub(r"\W", "_", n)} 0x{a:X}u' for n, a in code]
out += ['', '/* data labels */'] + [f'#define SYM_{re.sub(r"\W", "_", n)} 0x{a:X}u' for n, a in data]
trivial = [a for n, a in code if cg[n]['insns'] == 1]
out += ['', '/* one-instruction routines (shared rts, jump stubs) */', 'static const uint32_t trivial_syms[] = {' + ', '.join(f'0x{a:X}u' for a in trivial) + ', 0};']
out += ['', 'struct SymEntry { uint32_t addr; const char *name; };',
        f'static const struct SymEntry rom_syms[] = {{', *[f'    {{0x{a:X}u, "{n}"}},' for n, a in code], '};',
        f'static const struct SymEntry ram_syms[] = {{', *[f'    {{0x{o:04X}u, "{n}"}},' for o, n in ram], '};', '']
(P / 'src/symbols_gen.h').write_text('\n'.join(out))
print(f'src/symbols_gen.h: {len(code)} routines, {len(data)} data labels, {len(ram)} RAM symbols (from {src.name})')
