#!/usr/bin/env python3
"""Generate C byte arrays for the inline String data that follows printz / printsmallz / appendz /
printbigz calls, from the preprocessed asm (build/asm/src, where the String macro is already
expanded to dc.w / dc.b). usage: gen_strings.py FILE.asm -o OUT.h
Each string is named str_<routine>_<n> (n counts the calls inside the routine)."""
import json, pathlib, re, sys
args = sys.argv[1:]
src = pathlib.Path(args[0]); out = pathlib.Path(args[args.index('-o') + 1])
root = pathlib.Path(__file__).resolve().parent.parent
syms = json.load(open(root / 'build' / 'asm' / 'symbols.json'))
syms = syms.get('symbols', syms)
def symval(name):
    v = syms.get(name)
    return v if isinstance(v, int) else (v.get('addr') if isinstance(v, dict) else None)
def evaluate(expr):
    expr = expr.strip()
    def repl(m):
        tok = m.group(0)
        if tok.startswith('$'): return str(int(tok[1:], 16))
        if re.match(r'^\d+$', tok): return tok
        v = symval(tok)
        if v is None: raise ValueError(f'unknown symbol {tok} in {expr}')
        return str(v)
    py = re.sub(r"\$[0-9A-Fa-f]+|[A-Za-z_]\w*|\d+", repl, expr)
    return eval(py, {"__builtins__": {}}) & 0xFF
lines = src.read_text(errors='replace').splitlines()
res = ['/* Generated by tools/gen_strings.py from %s. Do not edit. */' % src.name, '#pragma once', '#include <stdint.h>', '']
routine, counts = None, {}
i = 0
while i < len(lines):
    l = lines[i]; body = l.split(';')[0]
    m = re.match(r'^([A-Za-z_]\w*)', body)
    if m and not body.startswith('.'): routine = m.group(1)
    call = re.search(r'\b(bsr|jsr)(\.\w)?\s+\(?(printz|printsmallz|appendz|printbigz)\b', body)
    if call and i + 1 < len(lines) and re.search(r'\bdc\.[bw]\b', lines[i + 1].split(';')[0]):
        vals = []
        j = i + 1
        while j < len(lines):
            b = lines[j].split(';')[0]
            m2 = re.search(r'\bdc\.([bw])\s+(.*)', b)
            if not m2: break
            width = m2.group(1)
            for tok in re.findall(r"'(?:[^']|'')*'|[^,]+", m2.group(2)):
                tok = tok.strip()
                if not tok: continue
                if tok.startswith("'"):
                    vals += [ord(c) for c in tok[1:-1].replace("''", "'")]
                elif width == 'w':
                    v = evaluate(tok); vals += [(v >> 8) & 0xFF, v & 0xFF] if v > 0xFF else [0, v]
                else:
                    vals.append(evaluate(tok))
            j += 1
        n = counts.get(routine, 0) + 1; counts[routine] = n
        name = f'str_{routine}_{n}'
        res.append(f'static const uint8_t {name}[{len(vals)}] = {{ {", ".join(str(v) for v in vals)} }};   /* {src.name}:{i + 1} {call.group(3)} */')
        i = j
        continue
    i += 1
out.write_text('\n'.join(res) + '\n')
print(f'{sum(counts.values())} strings -> {out}')
