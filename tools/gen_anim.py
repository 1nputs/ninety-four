#!/usr/bin/env python3
"""Generate src/anim_gen.h: the SPA (animation) and SPF (frame run) offsets from frames94.asm.
They are `name = *-SPAlist ; $XXXX` lines; the comment carries the value."""
import re, pathlib
P = pathlib.Path(__file__).resolve().parents[1]
out = ['/* Generated by tools/gen_anim.py from frames94.asm. Do not edit. */', '#pragma once', '']
n = 0
for line in (P / 'ref/NHL94Genesis/src/frames94.asm').read_text(errors='replace').splitlines():
    m = re.match(r'^(SP[AF]\w*)\s*=\s*\*-SP[AF]list\s*;\s*\$([0-9A-Fa-f]+)', line)
    if m:
        out.append(f'#define {m.group(1)} 0x{int(m.group(2), 16):X}'); n += 1
        continue
    # SPF frame numbers: "SPFx = <expr> ; <decimal>" or "SPFx = <decimal>"
    m = re.match(r'^(SPF\w*)\s*=\s*(\d+)\s*(?:;.*)?$', line) or re.match(r'^(SPF\w*)\s*=\s*\S+\s*;\s*(\d+)\b', line)
    if m:
        out.append(f'#define {m.group(1)} {int(m.group(2))}'); n += 1
(P / 'src/anim_gen.h').write_text('\n'.join(out) + '\n')
print(f'src/anim_gen.h: {n} animation constants')
