#!/usr/bin/env python3
"""Generate native/routines_gen.h: the C function of each 68k routine with its ROM address, for
the native game's routine stack (native/lockstep.c: lockstep's lag frames, the states' game loop
wait). Every global function of src/ whose name is a routine of src/symbols_gen.h: the same set a
dynamic symbol lookup would find, without one (dladdr is POSIX only and needs -rdynamic). It
compiles src/*.c to a scratch directory and reads their symbols with nm. make gen runs it."""
import pathlib, re, subprocess, sys, tempfile

P = pathlib.Path(__file__).resolve().parents[1]
cc = sys.argv[1] if len(sys.argv) > 1 else 'gcc'
syms = dict((n, int(a, 16)) for a, n in re.findall(r'\{0x([0-9A-F]+)u, "(\w+)"\}', (P / 'src/symbols_gen.h').read_text()))
defined = set()
with tempfile.TemporaryDirectory() as tmp:
    for c in sorted((P / 'src').glob('*.c')):
        obj = pathlib.Path(tmp) / (c.stem + '.o')
        subprocess.run([cc, '-std=gnu11', '-O1', '-Isrc', '-c', str(c), '-o', str(obj)], cwd=P, check=True)
        out = subprocess.run(['nm', '-g', '--defined-only', str(obj)], capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            f = line.split()
            if len(f) == 3 and f[1] == 'T':
                defined.add(f[2].lstrip('_') if sys.platform == 'darwin' else f[2])
rows = sorted((syms[n], n) for n in defined if n in syms)
out = ['/* Generated by tools/gen_routines.py from the functions of src/ and src/symbols_gen.h. Do not edit. */',
       '#pragma once', '#include <stdint.h>', '#include "game.h"', '',
       '/* the C function of each ported 68k routine (global, named as the routine) and its ROM address */',
       'static const struct { void (*fn)(void); uint32_t addr; } routine_fns[] = {']
out += ['    { (void (*)(void))%s, 0x%Xu },' % (n, a) for a, n in rows]
out += ['};', '']
(P / 'native/routines_gen.h').write_text('\n'.join(out))
print('native/routines_gen.h: %d routines' % len(rows))
